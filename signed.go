type getResultParams struct {
	baseParams
	SerialNumber int `json:"serialNumber"`
}

// GetResult retrieves a previously generated Signed API result by its
// SerialNumber (as returned in SignedResult.SerialNumber). RANDOM.ORG
// stores signed results for a minimum of 24 hours so they can be retrieved
// again if, for example, the original response was lost to a network
// failure. It is a package-level function rather than a method because Go
// does not allow methods to introduce their own type parameters; T must
// match the data type originally generated (e.g. int64 for
// generateSignedIntegers, string for generateSignedUUIDs/Strings/Blobs,
// []int64 for generateSignedIntegerSequences, float64 for
// generateSignedDecimalFractions/Gaussians).
func GetResult[T any](ctx context.Context, r *Random, serialNumber int) (SignedResult[T], error) {
	params := getResultParams{
		baseParams:   baseParams{APIKey: r.apiKey},
		SerialNumber: serialNumber,
	}

	env, err := invokeRequest[signedResultEnvelope](ctx, r, "getResult", params)
	if err != nil {
		return SignedResult[T]{}, err
	}

	return decodeSignedResult[T](env)
}

type verifySignatureParams struct {
	Random    json.RawMessage `json:"random"`
	Signature string          `json:"signature"`
}

type verifySignatureResult struct {
	Authenticity bool `json:"authenticity"`
}

// VerifySignature verifies that random and signature — typically
// SignedResult.Random and SignedResult.Signature from a prior Signed API
// call — were produced by RANDOM.ORG and have not been tampered with. It
// reports the server's authenticity verdict; a false result with a nil
// error means the signature did not match, not that the call failed.
func (r *Random) VerifySignature(ctx context.Context, random json.RawMessage, signature string) (bool, error) {
	params := verifySignatureParams{
		Random:    random,
		Signature: signature,
	}

	result, err := invokeRequest[verifySignatureResult](ctx, r, "verifySignature", params)
	if err != nil {
		return false, err
	}

	return result.Authenticity, nil
}
