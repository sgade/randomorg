// Signed commands
// see https://api.random.org/json-rpc/4/signed

// License describes the terms under which the random values in a
// SignedResult may be used, as selected by the owner of the API key that
// generated them.
type License struct {
	Type    string  `json:"type"`
	Text    string  `json:"text"`
	InfoURL *string `json:"infoUrl"`
}

// LicenseData carries information required by certain license types (e.g.
// Flexible Gambling), specifying the Maximum Payout Value (MPV) for the
// game round or lottery draw whose outcome the random values decide.
type LicenseData struct {
	MaxPayoutValue MaxPayoutValue `json:"maxPayoutValue"`
}

// MaxPayoutValue is an amount in a RANDOM.ORG-supported currency (USD, EUR,
// GBP, CAD, AUD, BTC, ETH), identified by an ISO 4217-style currency code.
type MaxPayoutValue struct {
	Currency string  `json:"currency"`
	Amount   float64 `json:"amount"`
}

// TicketData identifies the ticket chain position consumed by a signed
// generate call. It is present in a SignedResult only when the request
// specified a TicketID.
type TicketData struct {
	TicketID         string  `json:"ticketId"`
	PreviousTicketID *string `json:"previousTicketId"`
	NextTicketID     *string `json:"nextTicketId"`
}

// SignedResult is the response from a Signed API generate method or
// GetResult: the random values plus everything needed to prove they were
// generated by RANDOM.ORG.
type SignedResult[T any] struct {
	Method         string
	HashedAPIKey   string
	Data           []T
	License        License
	LicenseData    json.RawMessage
	UserData       json.RawMessage
	TicketData     *TicketData
	CompletionTime time.Time
	SerialNumber   int

	// Random is the raw, unmodified "random" object exactly as returned by
	// RANDOM.ORG. Pass it together with Signature to VerifySignature —
	// re-encoding the typed fields above is not guaranteed to reproduce the
	// exact bytes RANDOM.ORG signed.
	Random    json.RawMessage
	Signature string

	Cost          float64
	BitsUsed      int
	BitsLeft      int
	RequestsLeft  int
	AdvisoryDelay int
}

// signedResultEnvelope is the JSON-RPC result payload of every Signed API
// generate method, and of getResult.
type signedResultEnvelope struct {
	Random        json.RawMessage `json:"random"`
	Signature     string          `json:"signature"`
	Cost          float64         `json:"cost"`
	BitsUsed      int             `json:"bitsUsed"`
	BitsLeft      int             `json:"bitsLeft"`
	RequestsLeft  int             `json:"requestsLeft"`
	AdvisoryDelay int             `json:"advisoryDelay"`
}

// signedRandomEnvelope is the shape of the "random" object nested in
// signedResultEnvelope. It is method-agnostic: fields that only exist for
// some methods (e.g. min/max, characters) are decoded separately by callers
// that need them, since SignedResult only surfaces the fields common to
// every Signed API method.
type signedRandomEnvelope[T any] struct {
	Method         string          `json:"method"`
	HashedAPIKey   string          `json:"hashedApiKey"`
	Data           []T             `json:"data"`
	License        License         `json:"license"`
	LicenseData    json.RawMessage `json:"licenseData"`
	UserData       json.RawMessage `json:"userData"`
	TicketData     *TicketData     `json:"ticketData"`
	CompletionTime string          `json:"completionTime"`
	SerialNumber   int             `json:"serialNumber"`
}

// decodeSignedResult unpacks a signedResultEnvelope's raw "random" object
// into a typed SignedResult[T]. It is shared by every GenerateSigned*
// method, GetResult, and DecodeTicketResult.
func decodeSignedResult[T any](env signedResultEnvelope) (SignedResult[T], error) {
	if env.Random == nil {
		return SignedResult[T]{}, ErrJSONFormat
	}

	var randomEnv signedRandomEnvelope[T]
	if err := json.Unmarshal(env.Random, &randomEnv); err != nil {
		return SignedResult[T]{}, err
	}
	if randomEnv.Data == nil {
		return SignedResult[T]{}, ErrJSONFormat
	}

	completionTime, err := parseAPITime(randomEnv.CompletionTime)
	if err != nil {
		return SignedResult[T]{}, err
	}

	return SignedResult[T]{
		Method:         randomEnv.Method,
		HashedAPIKey:   randomEnv.HashedAPIKey,
		Data:           randomEnv.Data,
		License:        randomEnv.License,
		LicenseData:    randomEnv.LicenseData,
		UserData:       randomEnv.UserData,
		TicketData:     randomEnv.TicketData,
		CompletionTime: completionTime,
		SerialNumber:   randomEnv.SerialNumber,
		Random:         env.Random,
		Signature:      env.Signature,
		Cost:           env.Cost,
		BitsUsed:       env.BitsUsed,
		BitsLeft:       env.BitsLeft,
		RequestsLeft:   env.RequestsLeft,
		AdvisoryDelay:  env.AdvisoryDelay,
	}, nil
}

// signedGenerate invokes method, decodes its signed result into a
// SignedResult[T], and merges the response's bitsLeft/requestsLeft into the
// client's usage cache, mirroring generate's behavior for the Basic API.
func signedGenerate[T any](ctx context.Context, r *Random, method string, params any) (SignedResult[T], error) {
	env, err := invokeRequest[signedResultEnvelope](ctx, r, method, params)
	if err != nil {
		return SignedResult[T]{}, err
	}

	result, err := decodeSignedResult[T](env)
	if err != nil {
		return SignedResult[T]{}, err
	}

	bitsLeft, requestsLeft := env.BitsLeft, env.RequestsLeft
	r.mergeUsage(usageFields{BitsLeft: &bitsLeft, RequestsLeft: &requestsLeft})

	return result, nil
}

// SignedCommonOptions holds the optional parameters shared by every
// GenerateSigned* method.
type SignedCommonOptions struct {
	// PregeneratedRandomization selects historical randomness instead of
	// fresh, on-the-fly randomness. nil (the default) uses fresh randomness.
	PregeneratedRandomization *PregeneratedRandomization
	// LicenseData carries data required by some license types (e.g. the
	// Flexible Gambling license's maximum payout value); required for such
	// license types. nil (the default) omits it.
	LicenseData *LicenseData
	// UserData is included, unmodified, in the signed response alongside
	// the random data. Its JSON-encoded form must not exceed 1,000
	// characters. nil (the default) omits it.
	UserData any
	// TicketID, if set, consumes a ticket obtained from CreateTickets:
	// RANDOM.ORG records that the ticket was used to generate these values.
	// Each ticket can only be used once.
	TicketID string
}

// validateSignedCommonOptions validates the fields of SignedCommonOptions
// that can be checked client-side.
func validateSignedCommonOptions(o SignedCommonOptions) error {
	if err := validatePregeneratedRandomization(o.PregeneratedRandomization); err != nil {
		return err
	}
	if o.UserData != nil {
		encoded, err := json.Marshal(o.UserData)
		if err != nil {
			return err
		}
		if len(encoded) > 1_000 {
			return ErrParamRange
		}
	}
	return nil
}

// GenerateSignedIntegersOptions holds optional parameters for
// GenerateSignedIntegers and GenerateSignedIntegersWithBase.
type GenerateSignedIntegersOptions struct {
	// Replacement specifies whether the numbers are picked with
	// replacement. nil (the default) behaves like true.
	Replacement *bool
	SignedCommonOptions
}

type generateSignedIntegersParams struct {
	baseParams
	N                         int                        `json:"n"`
	Min                       int64                      `json:"min"`
	Max                       int64                      `json:"max"`
	Replacement               *bool                      `json:"replacement,omitempty"`
	Base                      int                        `json:"base,omitempty"`
	PregeneratedRandomization *PregeneratedRandomization `json:"pregeneratedRandomization,omitempty"`
	LicenseData               *LicenseData               `json:"licenseData,omitempty"`
	UserData                  any                        `json:"userData,omitempty"`
	TicketID                  string                     `json:"ticketId,omitempty"`
}

// GenerateSignedIntegers generates n number of digitally signed random
// integers in the range from min to max. Unlike GenerateIntegers, the
// result includes a Signature that can be used to prove the values were
// generated by RANDOM.ORG; see VerifySignature.
func (r *Random) GenerateSignedIntegers(ctx context.Context, n int, min, max int64, opts ...GenerateSignedIntegersOptions) (SignedResult[int64], error) {
	if n < 1 || n > 10_000 {
		return SignedResult[int64]{}, ErrParamRange
	}
	if min < -1_000_000_000 || min > 1_000_000_000 || max < -1_000_000_000 || max > 1_000_000_000 {
		return SignedResult[int64]{}, ErrParamRange
	}

	o := resolveOptions(opts)
	if err := validateSignedCommonOptions(o.SignedCommonOptions); err != nil {
		return SignedResult[int64]{}, err
	}

	params := generateSignedIntegersParams{
		baseParams:                baseParams{APIKey: r.apiKey},
		N:                         n,
		Min:                       min,
		Max:                       max,
		Replacement:               o.Replacement,
		PregeneratedRandomization: o.PregeneratedRandomization,
		LicenseData:               o.LicenseData,
		UserData:                  o.UserData,
		TicketID:                  o.TicketID,
	}

	return signedGenerate[int64](ctx, r, "generateSignedIntegers", params)
}

// GenerateSignedIntegersWithBase is GenerateSignedIntegers with the numbers
