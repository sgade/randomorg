// GenerateSignedIntegerSequences is the Signed API counterpart of
// GenerateIntegerSequences: it generates n digitally signed sequences,
// where sequence i has length[i] elements drawn from [min[i], max[i]].
func (r *Random) GenerateSignedIntegerSequences(ctx context.Context, n int, length []int, min, max []int64, opts ...GenerateSignedIntegerSequencesOptions) (SignedResult[[]int64], error) {
	if err := validateSequenceParams(n, length, min, max); err != nil {
		return SignedResult[[]int64]{}, err
	}

	o := resolveOptions(opts)
	if o.Replacement != nil && len(o.Replacement) != n {
		return SignedResult[[]int64]{}, ErrParamRange
	}
	if err := validateSignedCommonOptions(o.SignedCommonOptions); err != nil {
		return SignedResult[[]int64]{}, err
	}

	params := generateSignedIntegerSequencesParams{
		baseParams:                baseParams{APIKey: r.apiKey},
		N:                         n,
		Length:                    length,
		Min:                       min,
		Max:                       max,
		Replacement:               o.Replacement,
		PregeneratedRandomization: o.PregeneratedRandomization,
		LicenseData:               o.LicenseData,
		UserData:                  o.UserData,
		TicketID:                  o.TicketID,
	}

	return signedGenerate[[]int64](ctx, r, "generateSignedIntegerSequences", params)
}

// GenerateSignedIntegerSequencesWithBase is GenerateSignedIntegerSequences
// with each sequence displayed (and signed) in a non-decimal base: base
// must have exactly n elements, each 2, 8 or 16.
func (r *Random) GenerateSignedIntegerSequencesWithBase(ctx context.Context, n int, length []int, min, max []int64, base []int, opts ...GenerateSignedIntegerSequencesOptions) (SignedResult[[]string], error) {
	if err := validateSequenceParams(n, length, min, max); err != nil {
		return SignedResult[[]string]{}, err
	}
	if len(base) != n {
		return SignedResult[[]string]{}, ErrParamRange
	}
	for _, b := range base {
		if b != 2 && b != 8 && b != 16 {
			return SignedResult[[]string]{}, ErrParamRange
		}
	}

	o := resolveOptions(opts)
	if o.Replacement != nil && len(o.Replacement) != n {
		return SignedResult[[]string]{}, ErrParamRange
	}
	if err := validateSignedCommonOptions(o.SignedCommonOptions); err != nil {
		return SignedResult[[]string]{}, err
	}

	params := generateSignedIntegerSequencesParams{
		baseParams:                baseParams{APIKey: r.apiKey},
		N:                         n,
		Length:                    length,
		Min:                       min,
		Max:                       max,
		Replacement:               o.Replacement,
		Base:                      base,
		PregeneratedRandomization: o.PregeneratedRandomization,
		LicenseData:               o.LicenseData,
		UserData:                  o.UserData,
		TicketID:                  o.TicketID,
	}

	return signedGenerate[[]string](ctx, r, "generateSignedIntegerSequences", params)
}

